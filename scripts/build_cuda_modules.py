#!/usr/bin/env python3
"""Generate/check native CUDA modules. Only `generate` needs the CUDA toolkit."""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ('mindgrab', 'model16chan18cls', 'mindmap', 'mindsnap')
ARCHES = (60, 70, 75, 80, 86, 89, 90)
PTX_ARCH = 90
NVCC_VERSION = '12.8.93'
DRIVER_API = 12080
PTX_VERSION = '8.7'
ABI = 3
FLAGS = ('-O3', '--use_fast_math', '-std=c++11', '--machine=64')
SOURCES = ('src/cuda_kernels.cuh', 'src/cuda_module.cu', 'src/cuda_variants.h',
           'src/model_specs.h', 'src/cuda_geometry.h', 'src/cuda_geometry_mindmap.h',
           'src/pve_constants.h', 'scripts/build_cuda_modules.py')
# Parameter order and widths form the Driver API ABI. pointer = device address;
# size = 64-bit size_t; int = signed 32-bit. Launch policy remains in the runner.
AUX = {
    'wmma_probe_kernel': ['pointer'],
    'moments_finish_kernel': ['pointer', 'pointer', 'pointer', 'pointer', 'pointer', 'int'],
    'norm_gelu_kernel': ['pointer', 'pointer', 'pointer', 'pointer', 'int'],
    'fill_rows_kernel': ['pointer', 'pointer', 'int', 'int'],
    'classify_u8_kernel': ['pointer'] * 7 + ['int'] * 3,
    'fill_labels_u8_kernel': ['pointer', 'pointer', 'int', 'int'],
    'tissue_priors_kernel': ['pointer'] * 7 + ['int'] * 3,
    'fill_priors_kernel': ['pointer', 'pointer', 'int', 'int'],
    'pve_blur_kernel': ['pointer', 'pointer', 'int'],
    'pve_support_kernel': ['pointer', 'pointer'],
    'checksum_kernel': ['pointer', 'pointer', 'size'],
    'fill_pattern_kernel': ['pointer', 'size'],
}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def geometry(root=ROOT, model="mindgrab"):
    name = "cuda_geometry_mindmap.h" if model in ("mindmap", "mindsnap") else "cuda_geometry.h"
    text = (root / "src" / name).read_text()
    entries = re.findall(r'^#define BC_CUDA_GEOMETRY_([A-Z_]+) ([0-9]+)$', text, re.M)
    names = ('DIM', 'MAX_CHANNELS', 'CS', 'THREADS', 'REDUCE_THREADS',
             'REDUCE_BLOCKS', 'CONV_VPT', 'CONV_THREADS', 'WMMA_TILE',
             'WMMA_WARPS', 'WMMA_SCRATCH')
    values = {name: int(value) for name, value in entries}
    if len(entries) != len(names) or set(values) != set(names) or min(values.values()) <= 0:
        raise ValueError('invalid CUDA geometry contract')
    return values


def variants(root=ROOT):
    text = (root / 'src/cuda_variants.h').read_text()
    result = []
    for family, width in (('SCALAR', 2), ('WMMA', 1)):
        match = re.search(r'#define BC_CUDA_' + family + r'_VARIANTS\(X\)\s+((?:[^\n]*\\\n)*[^\n]*)', text)
        if not match:
            raise ValueError('missing variant catalog: ' + family)
        body = match[1].replace('\\\n', ' ')
        entries = re.findall(r'X\(([^)]+)\)', body)
        if re.sub(r'X\([^)]+\)', '', body).strip():
            raise ValueError('unsupported variant catalog syntax: ' + family)
        values = [tuple(int(n.strip()) for n in entry.split(',')) for entry in entries]
        if not values or any(len(v) != width or min(v) <= 0 for v in values) or len(set(values)) != len(values):
            raise ValueError('invalid/duplicate variants: ' + family)
        result.append(values)
    return result


def kernels(root=ROOT):
    scalar, wmma = variants(root)
    entries = []
    for v, t in scalar:
        entries.append(dict(id=f'scalar_{v}_{t}', symbol=f'_Z13conv3d_kernelILi{v}ELi{t}EEvPK6__halfPS0_S2_PdPKjPKfiiiii',
                            parameters=['pointer'] * 6 + ['int'] * 5, vpt=v, threads=t))
    for w, in wmma:
        entries.append(dict(id=f'wmma_{w}', symbol=f'_Z18conv3d_wmma_kernelILi{w}EEvPK6__halfPS0_S2_PdPKjPKfii',
                            parameters=['pointer'] * 6 + ['int'] * 2, warps=w))
    entries.extend(dict(id=name, symbol=name, parameters=params) for name, params in AUX.items())
    return entries


def source_hashes(root=ROOT):
    paths = list(SOURCES)
    for model in MODELS:
        paths.extend(f'src/models/{model}/{name}' for name in ('model_def.h', 'model.json', 'model_meta.json'))
    return {path: digest((root / path).read_bytes()) for path in paths}


def catalog(root=ROOT):
    scalar, wmma = variants(root)
    entries = {e['id']: e for e in kernels(root)}
    lines = ['/* Generated by scripts/build_cuda_modules.py; do not edit. */',
             '#ifndef BRAINCHOP_CUDA_MODULE_CATALOG_H', '#define BRAINCHOP_CUDA_MODULE_CATALOG_H',
             f'#define BC_CUDA_MODULE_ABI {ABI}', f'#define BC_CUDA_MODULE_DRIVER_API {DRIVER_API}']
    for i, model in enumerate(MODELS):
        lines.append(('#if' if i == 0 else '#elif') + ' defined(BC_MODEL_IS_' + model.upper() + ') && BC_MODEL_IS_' + model.upper())
        lines.extend(f'#define BC_CUDA_MODULE_{name} {value}' for name, value in geometry(root, model).items())
    lines.extend(['#else', '#error \"select a model before including the CUDA catalog\"', '#endif'])
    for name, values in [('SCALAR', scalar), ('WMMA', wmma)]:
        lines.append(f'#define BC_CUDA_MODULE_{name}(X) \\')
        for i, values_i in enumerate(values):
            key = name.lower() + '_' + '_'.join(map(str, values_i))
            tail = ' \\' if i + 1 < len(values) else ''
            lines.append(' X(' + ', '.join(map(str, values_i)) + ', "' + entries[key]['symbol'] + '")' + tail)
    lines.append('#define BC_CUDA_MODULE_AUX(X) \\')
    for i, name in enumerate(AUX):
        lines.append(f' X({name}, "{name}")' + (' \\' if i + 1 < len(AUX) else ''))
    return '\n'.join(lines + ['#endif', ''])


def run(args, cwd=ROOT / 'src'):
    p = subprocess.run(list(map(str, args)), cwd=cwd, text=True, capture_output=True)
    if p.returncode:
        raise ValueError(f'command failed: {args}\n{p.stdout}{p.stderr}')
    return p.stdout


def validate_exports(ptx, sass, expected):
    found = {}
    for name, params in re.findall(r'\.entry\s+([\w$]+)\s*\((.*?)\)', ptx, re.S):
        widths = re.findall(r'\.param\s+\.([ub]\d+)\s', params)
        found[name] = widths
    want = {e['symbol']: ['u32' if p == 'int' else 'u64' for p in e['parameters']] for e in expected}
    if found != want:
        raise ValueError(f'PTX entry ABI mismatch: missing={set(want)-set(found)}, extra={set(found)-set(want)}, '
                         f'parameters={[k for k in want.keys() & found.keys() if want[k] != found[k]]}')
    versions = set(re.findall(r'\.version\s+(\d+\.\d+)', ptx))
    targets = set(map(int, re.findall(r'\.target\s+sm_(\d+)', ptx)))
    if versions != {PTX_VERSION} or targets != {PTX_ARCH} or re.search(r'\.extern\s+\.func', ptx):
        raise ValueError(f'unexpected PTX version ({versions}) / target ({targets}) or unresolved device-library function')
    images = {}
    for chunk in re.split(r'arch = sm_', sass)[1:]:
        functions = set(re.findall(r'Function\s*:\s*([\w$]+)', chunk))
        if not functions:  # cuobjdump also prints the PTX image's header here.
            continue
        arch = int(re.match(r'\d+', chunk)[0])
        if arch in images:
            raise ValueError('duplicate native architecture')
        images[arch] = functions
    if set(images) != set(ARCHES) or any(not set(want).issubset(v) for v in images.values()):
        raise ValueError('native image architecture/kernel inventory mismatch')


def verify(directory, root=ROOT):
    manifest = json.loads((directory / 'manifest.json').read_text())
    fixed = dict(schema_version=2, abi_version=ABI, nvcc_version=NVCC_VERSION,
                 minimum_driver_api=DRIVER_API, architectures=list(ARCHES), ptx_architecture=PTX_ARCH,
                 ptx_version=PTX_VERSION, compiler_flags=list(FLAGS), geometry={m: geometry(root, m) for m in MODELS}, sources=source_hashes(root), kernels=kernels(root))
    for key, value in fixed.items():
        if manifest.get(key) != value:
            raise ValueError('stale/invalid CUDA module metadata: ' + key)
    if (directory / 'catalog.h').read_text() != catalog(root):
        raise ValueError('stale CUDA module catalog')
    if set(manifest.get('models', {})) != set(MODELS):
        raise ValueError('missing/extra model modules')
    for model in MODELS:
        entry = manifest['models'][model]
        if entry.get('file') != model + '.fatbin':
            raise ValueError('invalid model module filename')
        blob = (directory / entry['file']).read_bytes()
        # CUDA fatbin magic; the hash checks all images, including compressed ones.
        if blob[:4] != b'\x50\xed\x55\xba' or entry != dict(file=model+'.fatbin', size=len(blob), sha256=digest(blob)):
            raise ValueError('corrupt CUDA module: ' + model)
    return manifest


def generate(directory, nvcc):
    for name in ('NVCC_PREPEND_FLAGS', 'NVCC_APPEND_FLAGS'):
        if os.environ.get(name):
            raise ValueError(f'unset {name}: module compiler flags must match the manifest')
    compiler = shutil.which(nvcc)
    if not compiler:
        raise ValueError('nvcc is needed only for generation; use `check` for ordinary artifact validation')
    version = run([compiler, '--version'])
    if not re.search(r'\bV' + re.escape(NVCC_VERSION) + r'\b', version):
        raise ValueError(f'generation is pinned to nvcc V{NVCC_VERSION}; found:\n{version}')
    inspector = Path(compiler).parent / 'cuobjdump'
    if not inspector.is_file():
        raise ValueError('cuobjdump must accompany nvcc')
    supported = set(map(int, re.findall(r'compute_(\d+)', run([compiler, '--list-gpu-arch']))))
    if not set(ARCHES).issubset(supported):
        raise ValueError('compiler does not cover every required architecture')
    directory.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='bc-cuda-modules-', dir=directory.parent) as tmp:
        staging = Path(tmp)
        manifest = dict(schema_version=2, abi_version=ABI, nvcc_version=NVCC_VERSION,
                        minimum_driver_api=DRIVER_API, architectures=list(ARCHES), ptx_architecture=PTX_ARCH,
                        ptx_version=PTX_VERSION, compiler_flags=list(FLAGS), geometry={m: geometry(ROOT, m) for m in MODELS}, sources=source_hashes(), kernels=kernels(), models={})
        for model in MODELS:
            target = staging / (model + '.fatbin')
            args = [compiler, *FLAGS, '-DBC_MODEL_IS_' + model.upper() + '=1', '-Imodels/' + model, '--fatbin']
            for arch in ARCHES:
                args += ['-gencode', f'arch=compute_{arch},code=sm_{arch}']
            args += ['-gencode', f'arch=compute_{PTX_ARCH},code=compute_{PTX_ARCH}', 'cuda_module.cu', '-o', str(target)]
            run(args)
            validate_exports(run([inspector, '--dump-ptx', target]), run([inspector, '--dump-sass', target]), kernels())
            data = target.read_bytes()
            manifest['models'][model] = dict(file=target.name, size=len(data), sha256=digest(data))
            print(f'generated {model}: {len(data):,} bytes', flush=True)
        (staging / 'manifest.json').write_text(json.dumps(manifest, indent=2, sort_keys=True) + '\n')
        (staging / 'catalog.h').write_text(catalog())
        verify(staging)
        # No checked-in files are replaced until both model compilations and all
        # export/ABI checks pass. The manifest is published last.
        directory.mkdir(exist_ok=True)
        for name in [*(m + '.fatbin' for m in MODELS), 'catalog.h', 'manifest.json']:
            (staging / name).replace(directory / name)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('action', choices=('generate', 'check'))
    p.add_argument('--directory', type=Path, default=ROOT / 'src/cuda_modules')
    p.add_argument('--nvcc', default='nvcc')
    a = p.parse_args()
    try:
        if a.action == 'generate':
            generate(a.directory.resolve(), a.nvcc)
        verify(a.directory.resolve())
    except (ValueError, OSError, KeyError, TypeError) as e:
        p.exit(1, str(e) + '\n')
    print('CUDA modules: all models, source hashes, ABI and artifact hashes verified')


if __name__ == '__main__':
    main()
